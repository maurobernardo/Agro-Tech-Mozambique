function getValue(
  obj: { pt: string; en: string } | string,
  lang: Lang
): string {
  if (typeof obj === "string") return obj;
  return obj[lang];
}

export function useTranslations(lang: Lang) {
  return {
    get: (path: string) => {
      const keys = path.split(".");
      let current: unknown = t;
      for (const key of keys) {
        current = (current as Record<string, unknown>)?.[key];
      }
      const val = current as { pt: string; en: string } | string | undefined;
      return val ? getValue(val, lang) : path;
    },
  };
}
